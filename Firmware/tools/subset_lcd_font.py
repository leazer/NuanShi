"""Keep M5GFX efontCN_12 glyphs used by the firmware, with its original metrics."""

import ast
from pathlib import Path
import re


def main():
    project = Path(__file__).resolve().parent.parent
    source = project / ".pio/libdeps/m5stack-basic-bench/M5GFX/src/lgfx/Fonts/efont/lgfx_efont_cn.c"
    font = re.search(r"lgfx_efont_cn_12\[\d+\]\s*=\s*(.*?);\s*\n#endif", source.read_text(), re.S)[1]
    data = b"".join(ast.literal_eval("b" + s) for s in re.findall(r'"(?:[^"\\]|\\.)*"', font))
    paths = list((project / "src").glob("*.cpp")) + list((project / "src").glob("*.h"))
    used = {ord(c) for path in paths for c in path.read_text(encoding="utf-8")}

    def word(start):
        return int.from_bytes(data[start:start + 2], "big")

    # The 23-byte U8g2 header is followed by the Latin glyphs and a Unicode
    # index. Rebuild the index as one block, preserving each glyph's encoding.
    unicode_start = 23 + word(21)
    first_glyph = unicode_start + word(unicode_start)
    out = bytearray(data[:unicode_start])
    out.extend(b"\x00\x04\xff\xff")
    position = first_glyph
    while codepoint := word(position):
        size = data[position + 2]
        assert size >= 3
        if codepoint in used:
            out.extend(data[position:position + size])
        position += size
    out.extend(b"\x00\x00")
    lines = [
        "// Generated by tools/subset_lcd_font.py from M5GFX efontCN_12.",
        "// Copyright 2000-2003 /efont/ The Electronic Font Open Laboratory.",
        "// See ../licenses/efont.txt for the redistribution terms.",
        "#pragma once",
        "#include <M5Unified.h>",
        "",
        "static const uint8_t lcdSmallFontData[] PROGMEM = {",
    ]
    for offset in range(0, len(out), 16):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in out[offset:offset + 16]) + ",")
    lines.extend(["};", "static const lgfx::U8g2font lcdSmallFont = {lcdSmallFontData};", ""])
    (project / "src/lcd_small_font.h").write_text("\n".join(lines), encoding="ascii")
    print(f"Small LCD font: {len(data)} -> {len(out)} bytes")


if __name__ == "__main__":
    main()
